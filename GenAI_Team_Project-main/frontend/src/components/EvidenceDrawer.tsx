'use client';

import React from 'react';
import { X, FileText, CheckCircle2, ShieldAlert } from 'lucide-react';
import { useApp } from '@/context/AppContext';

export default function EvidenceDrawer() {
  const { activeEvidenceChunk, closeEvidenceDrawer } = useApp();

  if (!activeEvidenceChunk) return null;

  return (
    <div className="fixed inset-0 z-50 flex justify-end bg-charcoal/40 transition-opacity">
      <div className="relative flex h-full w-full max-w-lg flex-col border-l border-border bg-surface shadow-panel">
        {/* Drawer Header */}
        <div className="flex items-center justify-between border-b border-border px-5 py-4">
          <div className="flex items-center space-x-2.5">
            <div className="flex h-7 w-7 items-center justify-center rounded-md bg-primary/10 text-primary">
              <FileText className="h-4 w-4" />
            </div>
            <div>
              <h3 className="text-sm font-semibold text-charcoal">
                Retrieved Policy Evidence
              </h3>
              <p className="text-[11px] text-charcoal-muted">
                Verbatim chunk inspected from vector database
              </p>
            </div>
          </div>
          <button
            onClick={closeEvidenceDrawer}
            className="rounded-md p-1.5 text-charcoal-muted hover:bg-background hover:text-charcoal"
            aria-label="Close evidence inspector"
          >
            <X className="h-4 w-4" />
          </button>
        </div>

        {/* Verification Metadata Box */}
        <div className="border-b border-border bg-background/50 px-5 py-3">
          <div className="grid grid-cols-2 gap-3 text-xs">
            <div>
              <span className="text-[11px] text-charcoal-muted">Document Source:</span>
              <div className="font-medium text-charcoal truncate">
                {activeEvidenceChunk.metadata?.doc_title || 'Approved Policy Document'}
              </div>
            </div>
            <div>
              <span className="text-[11px] text-charcoal-muted">Location / Page:</span>
              <div className="font-medium text-charcoal">
                Page {activeEvidenceChunk.page_number} (Chunk #{activeEvidenceChunk.chunk_index})
              </div>
            </div>
          </div>
          {activeEvidenceChunk.similarity !== undefined && (
            <div className="mt-2 flex items-center space-x-1.5 text-[11px] text-primary font-medium">
              <CheckCircle2 className="h-3.5 w-3.5" />
              <span>Vector Relevance Score: {activeEvidenceChunk.similarity.toFixed(3)}</span>
            </div>
          )}
        </div>

        {/* Verbatim Content Area */}
        <div className="flex-1 overflow-y-auto p-5">
          <div className="mb-2 text-xs font-semibold uppercase tracking-wider text-charcoal-muted">
            Verbatim Document Text
          </div>
          <div className="rounded-md border border-border bg-background p-4 text-xs font-mono leading-relaxed text-charcoal whitespace-pre-wrap select-text">
            {activeEvidenceChunk.content}
          </div>

          <div className="mt-4 flex items-start space-x-2 rounded-md border border-border bg-surface p-3 text-[11px] text-charcoal-muted">
            <ShieldAlert className="h-4 w-4 shrink-0 text-primary mt-0.5" />
            <div>
              <strong className="text-charcoal font-semibold">Integrity Standard:</strong> This excerpt represents unedited text from authorized hostel records. Answers generated by the assistant are constrained strictly to verified statements in this document.
            </div>
          </div>
        </div>

        {/* Drawer Footer */}
        <div className="border-t border-border bg-surface p-4 text-right">
          <button
            onClick={closeEvidenceDrawer}
            className="rounded-md border border-border bg-background px-4 py-2 text-xs font-medium text-charcoal hover:bg-divider"
          >
            Close Inspector
          </button>
        </div>
      </div>
    </div>
  );
}
